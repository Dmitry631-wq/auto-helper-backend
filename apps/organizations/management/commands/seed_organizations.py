class Command(BaseCommand):
    help = 'Заполняет БД организациями, услугами и отзывами с разными датами'

    def handle(self, *args, **options):
        created_orgs = 0
        updated_orgs = 0
        created_reviews = 0
        now = timezone.now()

        for data in ORGANIZATIONS:
            reviews = data.pop('reviews', [])

            obj, was_created = Organization.objects.get_or_create(
                name=data['name'],
                defaults={**data, 'is_active': True},
            )
            if was_created:
                created_orgs += 1
                self.stdout.write(f'  ✓ создана: {obj.name}')
            else:
                # Обновляем services_list у существующих
                Organization.objects.filter(pk=obj.pk).update(
                    services_list=data.get('services_list', ''))
                updated_orgs += 1
                self.stdout.write(f'  ↻ обновлена: {obj.name}')

            for i, rev in enumerate(reviews):
                days_ago = rev.get('days_ago', 30)
                phone = f'+7999{i:04d}{obj.pk:04d}'
                user, _ = User.objects.get_or_create(
                    phone=phone,
                    defaults={
                        'username': f'reviewer_{i}_{obj.pk}',
                        'name': rev['author'],
                        'is_active': True,
                    }
                )
                review_obj, rev_created = Review.objects.get_or_create(
                    user=user,
                    organization=obj,
                    defaults={'rating': rev['rating'], 'text': rev['text']},
                )
                if rev_created:
                    created_reviews += 1
                    Review.objects.filter(pk=review_obj.pk).update(
                        created_at=now - timedelta(days=days_ago)
                    )

        self.stdout.write(self.style.SUCCESS(
            f'\nГотово! Создано: {created_orgs}, обновлено: {updated_orgs}, отзывов: {created_reviews}'
        ))